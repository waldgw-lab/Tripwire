import { test, expect, staffing, policy } from './claims-editor-fixture.mjs';

const normal = s => s.replace(/\s+/g, ' ').trim();
const openBatch = async (page, topic=staffing.topic) => {
  await page.getByTestId(`button-edit-group-${topic}`).click();
  await page.getByTestId('button-group-mode-articles').click();
  await expect(page.getByTestId('checkbox-group-page')).toBeVisible();
};

test('focus detail mirrors preview and keeps merged secondary context collapsed', async ({page,editorState:s}) => {
  s.summaries[0].developments=['First development'];
  s.summaries[0].relatedSubjects=['First related subject'];
  s.summaries[0].secondaryCategories=[s.categories[1]];
  s.summaries[1].developments=['Second development'];
  s.summaries[1].relatedSubjects=['Second related subject'];
  await page.goto(`/claims?category=${staffing.category}&topic=${staffing.topic}`);
  const preview=page.getByTestId(`text-topic-counts-${staffing.category}-${staffing.topic}`);
  await expect(page.getByTestId('text-focus-header-counts')).toBeVisible();
  expect(normal(await page.getByTestId('text-focus-header-counts').textContent())).toBe(normal(await preview.textContent()));
  await expect(page.getByTestId('text-focus-developments')).toContainText('First development');
  await expect(page.getByTestId('text-focus-developments')).toContainText('Second development');
  const extra=page.getByTestId('details-focus-tags');
  await expect(extra).not.toHaveAttribute('open','');
  await expect(page.getByTestId('secondary-category-tags')).not.toBeVisible();
  await extra.locator('summary').click();
  await expect(page.getByTestId('secondary-category-tags')).toBeVisible();
  await expect(page.getByTestId('text-related-subjects')).toContainText('First related subject');
  await expect(page.getByTestId('text-related-subjects')).toContainText('Second related subject');
  await page.goto('/claims?claim=shared');
  await expect(page.getByTestId('text-claim-scope-counts')).toContainText('article');
  await expect(page.getByTestId('details-focus-tags')).not.toHaveAttribute('open','');
});

test('selected articles save together, preserve drafts on conflict and reset without changing the shared label', async ({page,editorState:s}) => {
  await page.goto('/claims');
  await openBatch(page);
  await expect(page.getByTestId('text-batch-selected')).toContainText('0 of max 100 selected');
  await page.getByTestId('checkbox-group-article-staff-new').check();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  expect(s.writes).toHaveLength(0);
  await openBatch(page);
  await page.getByTestId('checkbox-group-page').check();
  await expect(page.getByTestId('text-batch-selected')).toContainText('2 of max 100 selected');
  await page.getByTestId('select-batch-category').selectOption(policy.category);
  await page.getByTestId('input-batch-label').fill('Reviewed staffing subset');
  await page.getByTestId('input-batch-reason').fill('Review checked articles together');
  await expect(page.getByTestId('button-save-batch')).toBeDisabled();
  await page.getByTestId('checkbox-confirm-batch').check();
  const routePattern='**/api/tripwire/focus-groups/*/article-corrections';
  await page.route(routePattern,r=>r.fulfill({status:409,json:{error:'Group changed; nothing saved'}}));
  await page.getByTestId('button-save-batch').click();
  await expect(page.getByTestId('batch-error')).toContainText('nothing saved');
  await expect(page.getByTestId('input-batch-label')).toHaveValue('Reviewed staffing subset');
  await expect(page.getByTestId('text-batch-selected')).toContainText('2 of max 100 selected');
  expect(s.writes).toHaveLength(0);
  await page.unroute(routePattern);
  await page.getByTestId('checkbox-confirm-batch').check();
  await page.getByTestId('button-save-batch').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect(s.writes).toHaveLength(1);
  expect(s.groups).toEqual({});
  expect(s.records.find(a=>a.id==='policy').focusOverride).toBeUndefined();
  for(const id of ['staff-new','staff-old'])expect(s.records.find(a=>a.id===id).focusOverride.topicTitle).toBe('Reviewed staffing subset');
  await page.reload();
  const topic=s.records.find(a=>a.id==='staff-new').focusOverride.topicId;
  await expect(page.getByTestId(`detail-focus-${topic}`)).toContainText('Reviewed staffing subset');
  await openBatch(page,topic);
  await page.getByTestId('checkbox-group-page').check();
  await page.getByTestId('button-reset-batch').click();
  await page.getByTestId('input-batch-reason').fill('Return the checked articles to automatic');
  await page.getByTestId('checkbox-confirm-batch').check();
  await page.getByTestId('button-save-batch').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  for(const id of ['staff-new','staff-old'])expect(s.records.find(a=>a.id===id).focusOverride).toBeNull();
  expect(s.writes).toHaveLength(2);
});

test('checkbox selection spans bounded pages, caps at 100 and rejects an outdated preview', async ({page,editorState:s}) => {
  const template=s.records.find(r=>r.id==='staff-old');
  for(let i=0;i<102;i++)s.records.push({...template,id:`staff-bulk-${i}`,title:`Synthetic browser-only staffing article ${i}`});
  await page.goto('/claims');
  await openBatch(page);
  await page.getByTestId('checkbox-group-page').check();
  await page.getByTestId('button-batch-next').click();
  await expect(page.getByTestId('text-batch-selected')).toContainText('50 of max 100 selected');
  await page.getByTestId('checkbox-group-page').check();
  await expect(page.getByTestId('text-batch-selected')).toContainText('100 of max 100 selected');
  await page.getByTestId('button-batch-next').click();
  const rows=page.locator('input[data-testid^="checkbox-group-article-"]');
  await expect(rows).toHaveCount(4);
  await expect(rows.first()).toBeDisabled();
  await page.getByTestId('button-batch-prev').click();
  await expect(page.getByTestId('checkbox-group-page')).toBeChecked();
  s.token++;
  await page.getByTestId('button-batch-next').click();
  await expect(page.getByRole('alert')).toContainText('Group membership changed');
  await expect(page.getByTestId('button-save-batch')).toBeDisabled();
  expect(s.writes).toHaveLength(0);
});
